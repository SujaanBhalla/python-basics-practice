# This program generates a fun band name by combining: 
# 1. The city where the user grew up. 
# 2. The user's pet name.

# STEP 1: Display a welcome message
print("Welcome to the Band Name Generator!")

# STEP 2: Ask the user for the city they grew up in
city = input("What's the name of the city you grew up in?\n")

# STEP 3: Ask the user for their pet's name
pet = input("What's your pet's name?\n")

# STEP 4: Generate and display the band name
print("Your band name could be: " + city + " " + pet)

